// Embeds the authored V9 report shell (src/report/templates/report.html) into src/report/template.js,
// so the renderer stays a module with no file access.
// Usage: node tools/report-template.mjs          write src/report/template.js
//        node tools/report-template.mjs --check  fail unless src/report/template.js reproduces from the shell
import { createHash } from 'node:crypto';
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';

const source = new URL('../src/report/templates/report.html', import.meta.url);
const target = new URL('../src/report/template.js', import.meta.url);

/** The generated module for one authored shell. Line endings are normalized so CRLF checkouts generate identical bytes. */
export function templateModule(authored) {
  const html = authored.replace(/\r\n/g, '\n');
  const sha256 = createHash('sha256').update(html).digest('hex');
  return { sha256, module: `// Generated by tools/report-template.mjs from src/report/templates/report.html. Do not edit.
export const TEMPLATE_SOURCE_SHA256 = '${sha256}';
export const TEMPLATE = ${JSON.stringify(html)};
` };
}

/** Whether src/report/template.js is exactly what the authored shell generates. */
export async function templateCurrent() {
  const { sha256, module } = templateModule(await readFile(source, 'utf8'));
  let current = null;
  try { current = (await readFile(target, 'utf8')).replace(/\r\n/g, '\n'); } catch { /* reported by the caller */ }
  return { current: current === module, sha256 };
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  if (process.argv.includes('--check')) {
    const { current, sha256 } = await templateCurrent();
    if (!current) {
      console.error('src/report/template.js does not match src/report/templates/report.html; run: node tools/report-template.mjs');
      process.exit(1);
    }
    console.log(`template reproduces from the authored shell (sha256 ${sha256})`);
  } else {
    const { sha256, module } = templateModule(await readFile(source, 'utf8'));
    await writeFile(target, module);
    console.log(`wrote src/report/template.js (sha256 ${sha256})`);
  }
}
